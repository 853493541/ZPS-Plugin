import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';

const url = process.env.PREVIEW_URL || 'http://127.0.0.1:4190';
const fixture = JSON.parse(await fs.readFile('app/tests/fixtures/jx3box/std-12784-level-1.json', 'utf8'));
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const result = query => ({ list: String(query.id) === '12784' ? fixture.raw.list : [], raw: String(query.id) === '12784' ? fixture.raw : { list: [] }, total: String(query.id) === '12784' ? 1 : 0, client: query.client, source: 'cache', stale: false, cachedAt: Date.now() });
  await page.route('**/preview-api/lookupCached', route => route.fulfill({ json: { result: route.request().postDataJSON().payload.map(result) } }));
  await page.route('**/preview-api/lookup', route => route.fulfill({ json: { result: result(route.request().postDataJSON().payload) } }));
  await page.route('**/preview-api/loadIcon', route => route.fulfill({ status: 400, json: { error: 'Controlled offline icon state' } }));
  await page.goto(url);
  await page.waitForSelector('.type-item');
  const snapshot = async () => (await (await page.request.post(new URL('/preview-api/activateFeature', url).href, { data: { payload: 'jx-buff' } })).json()).result;
  const original = await snapshot();
  const datasetA = original.datasetId;
  const tab = id => page.locator(`.dataset-tab-item[data-dataset-id="${id}"] .dataset-tab`);
  const closeTab = id => page.locator(`.dataset-tab-item[data-dataset-id="${id}"] .dataset-close`);
  async function selectDataset(id) {
    await tab(id).click();
    await page.waitForFunction(id => document.querySelector(`.dataset-tab-item[data-dataset-id="${id}"] .dataset-tab`)?.getAttribute('aria-selected') === 'true', id);
  }
  async function openBuff() {
    await page.locator('#type-search').fill('12784');
    await page.locator('#type-list .type-item').click();
    await page.locator('#type-members [data-key="buff:12784"] .type-member-open').click();
    await page.waitForSelector('#detail-modal[open]');
  }
  assert.equal(await page.locator('#breadcrumb-name').innerText(), 'BuffData.jx3dat');
  assert.equal(await page.locator('#dataset-version').innerText(), '版本未标注');
  await openBuff();
  await page.locator('[name="nPower"]').fill('71');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#detail-modal').isVisible(), false);
  await page.locator('#new-button').click();
  await page.locator('#modal [name="filename"]').fill('BuffData.jx3dat');
  await page.locator('#modal [name="gameVersion"]').fill('预案 B');
  await page.locator('#modal-submit').click();
  await page.waitForFunction(() => document.querySelectorAll('.dataset-tab').length === 2);
  const current = await snapshot();
  const datasetB = current.datasetId;
  assert.notEqual(datasetA, datasetB);
  assert.equal(current.gameVersion, '预案 B');
  assert.equal(await page.locator('#dataset-version').innerText(), '版本 预案 B');
  assert.equal(current.document.records.length, 0);
  await page.locator('#add-type-button').click();
  await page.locator('#modal [name="name"]').fill('团队控制');
  await page.locator('#modal-submit').click();
  await page.waitForFunction(() => document.querySelector('#type-detail-header h2')?.textContent === '团队控制');
  await page.locator('#assign-member-button').click();
  await page.getByRole('textbox', { name: '输入 Buff ID', exact: true }).fill('12784');
  await page.locator('#modal-submit').click();
  await page.waitForSelector('#type-members [data-key="buff:12784"]');
  await openBuff();
  await page.locator('[name="nPower"]').fill('99');
  await page.getByRole('button', { name: '保存条目修改' }).click();
  await page.waitForFunction(() => document.querySelector('[name="nPower"]')?.value === '99');
  await page.locator('.inspector-close').click();
  await selectDataset(datasetA);
  await openBuff();
  assert.equal(await page.locator('[name="nPower"]').inputValue(), '71', 'dataset A retains unapplied draft independently');
  await page.getByRole('button', { name: '保存条目修改' }).click();
  await page.waitForFunction(() => !document.querySelector('#undo-button').disabled);
  await page.locator('.inspector-close').click();
  await selectDataset(datasetB);
  await openBuff();
  assert.equal(await page.locator('[name="nPower"]').inputValue(), '99');
  await page.locator('.inspector-close').click();
  await page.locator('#undo-button').click();
  await openBuff();
  assert.equal(await page.locator('[name="nPower"]').inputValue(), '10', 'undo in B does not undo A');
  const bounds = await page.locator('#detail-modal').boundingBox();
  assert.ok(bounds.width >= 850 && Math.abs(bounds.x + bounds.width / 2 - 720) < 2, 'detail editor is large and centered');
  assert.equal(await page.locator('#detail-owner-file').innerText(), 'BuffData.jx3dat');
  await page.locator('#box-tab').click();
  await fs.mkdir('artifacts', { recursive: true });
  await page.screenshot({ path: 'artifacts/datasets-modal.png' });
  await page.keyboard.press('Escape');
  await page.screenshot({ path: 'artifacts/datasets-workspace.png' });
  await page.locator('#dataset-info-button').click();
  assert.match(await page.locator('#modal-content').innerText(), /预案 B/);
  assert.match(await page.locator('#modal-content').innerText(), /当前内容指纹/);
  await page.locator('#modal-cancel').click();
  await openBuff();
  await page.locator('[name="nPower"]').fill('123');
  await page.keyboard.press('Escape');
  const canceled = page.waitForEvent('dialog').then(dialog => dialog.dismiss());
  await closeTab(datasetB).click(); await canceled;
  assert.equal(await tab(datasetB).getAttribute('aria-selected'), 'true');
  await openBuff();
  assert.equal(await page.locator('[name="nPower"]').inputValue(), '123', 'canceling dataset close preserves draft');
  await page.keyboard.press('Escape');
  const discarded = page.waitForEvent('dialog').then(dialog => dialog.accept());
  await closeTab(datasetB).click(); await discarded;
  await page.waitForFunction(id => !document.querySelector(`.dataset-tab-item[data-dataset-id="${id}"]`), datasetB);
  await openBuff();
  assert.equal(await page.locator('[name="nPower"]').inputValue(), '71', 'closing B leaves A applied bytes intact');
  await page.keyboard.press('Escape');
  const discardedA = page.waitForEvent('dialog').then(dialog => dialog.accept());
  await closeTab(datasetA).click(); await discardedA;
  await page.waitForFunction(() => document.querySelectorAll('.dataset-tab').length === 0);
  assert.equal(await page.locator('#empty-create').isVisible(), true);
  assert.equal(await page.locator('#feature-tab-jx-buff').getAttribute('aria-selected'), 'true');
  await page.getByRole('tab', { name: '茗伊聊天监控' }).click();
  await page.waitForSelector('#records-body tr');
  await page.getByRole('tab', { name: '剑心 BUFF增强' }).click();
  await page.waitForFunction(() => document.querySelector('#feature-tab-jx-buff')?.getAttribute('aria-selected') === 'true' && document.querySelector('#feature-panel-jx-buff')?.getAttribute('aria-busy') === 'false');
  assert.equal(await page.locator('.dataset-tab').count(), 0, 'closed feature stays empty instead of reopening a sample');
  await page.setViewportSize({ width: 1050, height: 760 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.deepEqual(errors, []);
  console.log('PASS same-name datasets, visible file/version, independent drafts/applied bytes/undo, centered modal/Escape, guarded close/cancel, explicit empty feature, compact layout');
} finally {
  await browser.close();
}
