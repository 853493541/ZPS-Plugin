import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';

const url = process.env.PREVIEW_URL || 'http://127.0.0.1:4185';
const fixture = JSON.parse(await fs.readFile('app/tests/fixtures/jx3box/std-12784-level-1.json', 'utf8'));
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const result = query => ({ list: String(query.id) === '12784' ? fixture.raw.list : [], raw: String(query.id) === '12784' ? fixture.raw : { list: [] }, total: String(query.id) === '12784' ? 1 : 0, client: query.client, source: 'cache', stale: false, cachedAt: Date.now() });
  await page.route('**/preview-api/lookupCached', route => route.fulfill({ json: { result: route.request().postDataJSON().payload.map(result) } }));
  await page.route('**/preview-api/lookup', route => route.fulfill({ json: { result: result(route.request().postDataJSON().payload) } }));
  await page.route('**/preview-api/loadIcon', route => route.fulfill({ status: 400, json: { error: 'Offline icon test' } }));
  page.on('dialog', dialog => dialog.accept());
  await page.goto(url);
  await page.waitForSelector('#type-list .type-item');
  assert.equal(await page.locator('#type-list .type-item').count(), 100);
  assert.equal(await page.locator('#editor-grid').isVisible(), false, 'details must not crowd the initial workspace');
  assert.equal(await page.locator('#feature-tabs').getAttribute('aria-orientation'), 'vertical');
  assert.equal(await page.locator('#feature-tabs button').count(), 4);
  assert.ok(await page.locator('#type-list .type-name').first().evaluate(node => parseFloat(getComputedStyle(node).fontSize)) >= 16);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);

  await page.locator('#type-search').fill('逃兵');
  await page.waitForFunction(() => document.querySelectorAll('#type-list .type-item').length === 1);
  await page.locator('#type-list .type-item').click();
  const originalType = await page.locator('#type-name').innerText();
  assert.match(await page.locator('#type-members').innerText(), /逃兵/);
  await page.locator('.type-member-row').click();
  await page.locator('[name="nPower"]').fill('13');
  await page.locator('.inspector-close').click();
  await page.locator('#type-search').fill('');
  await page.locator('#type-list .type-item').first().click();
  await page.locator('#type-search').fill('12784');
  await page.locator('#type-list .type-item').click();
  await page.locator('.type-member-row').click();
  assert.equal(await page.locator('[name="nPower"]').inputValue(), '13', 'closing and returning must preserve unapplied draft');
  await page.getByRole('button', { name: '保存条目修改' }).click();
  await page.waitForFunction(() => !document.querySelector('#undo-button').disabled);
  await page.locator('[name="nClass"]').selectOption('沉默');
  await page.getByRole('button', { name: '保存条目修改' }).click();
  await page.waitForFunction(() => !document.querySelector('#modal')?.open && document.querySelector('[name="nClass"]')?.value === '沉默');
  const snapshot = async () => (await (await page.request.post(new URL('/preview-api/activateFeature', url).href, { data: { payload: 'jx-buff' } })).json()).result;
  let current = await snapshot();
  assert.equal(current.document.records.find(record => record.id === 12784).fields.nClass, '沉默');
  assert.equal(current.document.records.find(record => record.id === 12784).fields.nPower, 13);
  await page.locator('.inspector-close').click();
  await page.locator('#undo-button').click();
  await page.locator('.type-member-row').click();
  await page.waitForFunction(type => document.querySelector('[name="nClass"]')?.value === type, originalType);
  await page.locator('.inspector-close').click();

  await page.locator('#add-type-button').click();
  await page.locator('#modal [name="name"]').fill('草稿目标');
  await page.locator('#modal-submit').click();
  await page.waitForFunction(() => document.querySelector('#type-name')?.textContent === '草稿目标');
  await page.locator('#type-search').fill('12784');
  await page.locator('#type-list .type-item').click();
  await page.locator('.type-member-row').click();
  await page.locator('[name="nClass"]').selectOption('草稿目标');
  await page.locator('[name="nPower"]').fill('17');
  await page.locator('.inspector-close').click();
  await page.locator('#type-search').fill('草稿目标');
  await page.locator('#type-list .type-item').click();
  await page.locator('#type-name-edit').click();
  await page.locator('#type-name-input').fill('草稿新目标');
  await page.locator('#type-name-input').press('Enter');
  await page.waitForFunction(() => document.querySelector('#type-name')?.textContent === '草稿新目标');
  await page.locator('#type-search').fill('12784');
  await page.locator('#type-list .type-item').click();
  await page.locator('.type-member-row').click();
  assert.equal(await page.locator('[name="nClass"]').inputValue(), '草稿新目标', 'pending destination follows a type rename');
  assert.equal(await page.locator('[name="nPower"]').inputValue(), '17', 'unrelated buff draft survives a destination rename');
  await page.locator('[name="nClass"]').selectOption(originalType);
  await page.locator('[name="nPower"]').fill('13');
  await page.getByRole('button', { name: '保存条目修改' }).click();
  await page.locator('.inspector-close').click();

  await page.locator('#add-type-button').click();
  await page.locator('#modal [name="name"]').fill('工作流测试');
  await page.locator('#modal-submit').click();
  await page.waitForFunction(() => document.querySelector('#type-name')?.textContent === '工作流测试');
  await page.locator('#assign-member-button').click();
  await page.locator('#add-buff-id').fill('12784');
  await page.waitForSelector('#add-buff-move');
  assert.match(await page.locator('#add-buff-preview').innerText(), /一个 Buff 只能属于一个类型/, 'an existing buff is detected and not added twice');
  await page.locator('#modal-submit').click();
  assert.match(await page.locator('#toast').innerText(), /移到此类型/);
  await page.locator('#add-buff-move').click();
  await page.waitForSelector('#type-members [data-key="buff:12784"]');
  assert.match(await page.locator('#type-detail-header').innerText(), /1 个 Buff/);
  await page.locator('#type-name-edit').click();
  await page.locator('#type-name-input').fill('工作流重命名');
  await page.locator('#type-name-input').press('Enter');
  await page.waitForFunction(() => document.querySelector('#type-name')?.textContent === '工作流重命名');
  current = await snapshot();
  assert.equal(current.document.records.find(record => record.id === 12784).fields.nClass, '工作流重命名');
  await page.locator('#type-members [data-key="buff:12784"]').click();
  await page.locator('[name="nClass"]').selectOption('');
  await page.getByRole('button', { name: '保存条目修改' }).click();
  await page.waitForFunction(() => document.querySelector('.type-count-badge')?.textContent.startsWith('0 个 Buff'));
  current = await snapshot();
  assert.equal(current.document.records.find(record => record.id === 12784).fields.nClass, '');
  assert.equal(current.document.records.filter(record => record.key.startsWith('buff:')).length, 177, 'remove membership must retain rule');
  await page.locator('.inspector-close').click();
  await page.locator('#undo-button').click();
  await page.waitForFunction(() => document.querySelector('.type-count-badge')?.textContent.startsWith('1 个 Buff'));
  await fs.mkdir('artifacts', { recursive: true });
  await page.screenshot({ path: 'artifacts/type-workspace.png' });
  await page.locator('#type-members [data-key="buff:12784"]').click();
  await page.locator('#box-tab').click();
  assert.equal(await page.locator('#detail-modal').evaluate(node => node.open && node.matches(':modal')), true);
  const detailBox = await page.locator('#detail-modal').boundingBox();
  assert.ok(Math.abs(detailBox.x + detailBox.width / 2 - 720) <= 2 && Math.abs(detailBox.y + detailBox.height / 2 - 480) <= 2, 'record detail must be centered');
  await page.screenshot({ path: 'artifacts/type-buff-detail.png' });
  await page.setViewportSize({ width: 1050, height: 760 });
  const compactDetail = await page.locator('#detail-modal').boundingBox();
  assert.ok(compactDetail.x >= 0 && compactDetail.y >= 0 && compactDetail.x + compactDetail.width <= 1050 && compactDetail.y + compactDetail.height <= 760, 'compact modal must fit the viewport');
  await page.locator('.inspector-close').click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  const memberBox = await page.locator('#type-members').boundingBox();
  assert.ok(memberBox.width > 400 && memberBox.height > 250, 'smaller window must retain useful member workspace');
  assert.deepEqual(errors, []);
  console.log('PASS actual sample type/name/ID live search, readable navigation, draft retention, membership move/remove/undo, create/rename references, centered native detail modal, compact viewport');
} finally {
  await browser.close();
}
